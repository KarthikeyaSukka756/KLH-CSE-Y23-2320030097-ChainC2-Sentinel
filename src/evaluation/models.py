# ChainC2 Sentinel — Detection Evaluation Models
"""Structured models for evaluating detection performance under laboratory conditions.

Safety and Research Declarations:
- Ground-truth labels ("benign", "synthetic_c2") represent controlled laboratory scenario baselines.
- Evaluation metrics quantify the detectability of predefined synthetic C2-like sequences.
- No claim is made regarding real-world malware detection accuracy or attribution.
"""

from __future__ import annotations

import enum
from datetime import datetime, timezone
from typing import Any, Optional

from pydantic import BaseModel, ConfigDict, Field

from src.detection.models import DetectionResult, DetectionStatus


class GroundTruth(str, enum.Enum):
    """Controlled ground-truth classification for experimental scenario runs."""

    BENIGN = "benign"  # Scenario A negative control (legitimate Web3 activity)
    SYNTHETIC_C2 = "synthetic_c2"  # Scenario B positive control (synthetic C2-like activity)


class ClassificationVerdict(str, enum.Enum):
    """Binary classification outcome comparing detector verdict against ground truth."""

    TRUE_POSITIVE = "TP"  # Synthetic C2 correctly triggered
    TRUE_NEGATIVE = "TN"  # Benign control correctly not triggered
    FALSE_POSITIVE = "FP"  # Benign control incorrectly triggered
    FALSE_NEGATIVE = "FN"  # Synthetic C2 failed to trigger


class ExperimentRecord(BaseModel):
    """Detailed record of a single scenario execution, correlation, and detection evaluation."""

    model_config = ConfigDict(extra="forbid")

    experiment_id: str = Field(..., description="Unique experiment identifier")
    run_id: str = Field(..., description="Scenario run identifier")
    scenario_id: str = Field(..., description="Scenario identifier (e.g. scenario_a_benign, scenario_b_synthetic_c2)")
    ground_truth: GroundTruth = Field(..., description="Predefined laboratory ground truth")
    execution_status: str = Field(default="SUCCESS", description="Execution status ('SUCCESS', 'FAILED')")
    total_events: int = Field(..., description="Number of raw telemetry events captured")
    stages_observed: list[str] = Field(
        default_factory=list, description="Telemetry layers observed in the sequence"
    )
    correlated_sequence_id: Optional[str] = Field(
        default=None, description="Identifier of the reconstructed CorrelatedSequence"
    )
    detection_status: DetectionStatus = Field(
        ..., description="Detector status ('triggered' or 'not_triggered')"
    )
    triggered: bool = Field(..., description="Boolean indicating whether detection rule triggered")
    rule_id: str = Field(..., description="Identifier of the detection rule evaluated")
    rule_version: str = Field(..., description="Version of the detection rule evaluated")
    classification: ClassificationVerdict = Field(
        ..., description="Evaluation outcome: TP, TN, FP, or FN"
    )
    detection_latency_ms: Optional[float] = Field(
        default=None, description="Detection processing latency in milliseconds"
    )
    timestamp_start: datetime = Field(
        ..., description="Timestamp when scenario execution began"
    )
    timestamp_end: datetime = Field(
        ..., description="Timestamp when detection evaluation completed"
    )
    is_synthetic_fixture: bool = Field(
        default=False,
        description="Whether this record was generated by an artificial evaluation fixture (e.g. FP/FN test)"
    )
    detection_result: Optional[DetectionResult] = Field(
        default=None, description="Complete factual DetectionResult object"
    )
    details: dict[str, Any] = Field(
        default_factory=dict, description="Additional scenario metadata or context"
    )


class EvaluationMetrics(BaseModel):
    """Deterministic statistical evaluation metrics with explicit denominators."""

    model_config = ConfigDict(extra="forbid")

    total_experiments: int = Field(..., description="Total number of evaluated experiments")
    successful_runs: int = Field(..., description="Number of successful scenario executions")
    failed_runs: int = Field(..., description="Number of failed scenario executions")
    experiment_success_rate: float = Field(
        ..., description="Ratio of successful runs to total runs [successful_runs / total_experiments]"
    )

    # Confusion matrix raw counts
    ground_truth_positives: int = Field(
        ..., description="Total positive ground-truth cases [TP + FN]"
    )
    ground_truth_negatives: int = Field(
        ..., description="Total negative ground-truth cases [TN + FP]"
    )
    true_positives: int = Field(..., description="Count of correctly detected synthetic C2 cases (TP)")
    true_negatives: int = Field(..., description="Count of correctly non-triggered benign cases (TN)")
    false_positives: int = Field(..., description="Count of benign cases erroneously triggered (FP)")
    false_negatives: int = Field(..., description="Count of synthetic C2 cases missed (FN)")

    # Derived rates with safe zero-denominator handling (None when denominator == 0)
    detection_rate: Optional[float] = Field(
        default=None,
        description="Detection Rate / Recall / Sensitivity: TP / (TP + FN). None if (TP + FN) == 0."
    )
    false_positive_rate: Optional[float] = Field(
        default=None,
        description="False Positive Rate / Fall-out: FP / (FP + TN). None if (FP + TN) == 0."
    )
    precision: Optional[float] = Field(
        default=None,
        description="Precision / Positive Predictive Value: TP / (TP + FP). None if (TP + FP) == 0."
    )
    true_negative_rate: Optional[float] = Field(
        default=None,
        description="True Negative Rate / Specificity: TN / (TN + FP). None if (TN + FP) == 0."
    )
    accuracy: Optional[float] = Field(
        default=None,
        description="Overall Accuracy: (TP + TN) / total_experiments. None if total_experiments == 0."
    )
    f1_score: Optional[float] = Field(
        default=None,
        description="F1 Score: 2 * (Precision * Recall) / (Precision + Recall). None if undefined."
    )

    # Latency statistics
    average_detection_latency_ms: Optional[float] = Field(
        default=None, description="Average detection processing latency in milliseconds"
    )
    min_detection_latency_ms: Optional[float] = Field(
        default=None, description="Minimum detection processing latency in milliseconds"
    )
    max_detection_latency_ms: Optional[float] = Field(
        default=None, description="Maximum detection processing latency in milliseconds"
    )

    # Mathematical documentation
    metric_formulas: dict[str, str] = Field(
        default_factory=lambda: {
            "detection_rate": "TP / (TP + FN) [Denominator: Ground Truth Positives]",
            "false_positive_rate": "FP / (FP + TN) [Denominator: Ground Truth Negatives]",
            "precision": "TP / (TP + FP) [Denominator: All Triggered Detections]",
            "true_negative_rate": "TN / (TN + FP) [Denominator: Ground Truth Negatives]",
            "accuracy": "(TP + TN) / total_experiments [Denominator: Total Experiments]",
            "f1_score": "2 * (Precision * Recall) / (Precision + Recall)",
            "experiment_success_rate": "successful_runs / total_experiments",
        },
        description="Explicit mathematical definitions and denominators for all metrics"
    )


class AggregateEvaluationResult(BaseModel):
    """Comprehensive machine-readable evaluation report preserving individual experiments and metrics."""

    model_config = ConfigDict(extra="forbid")

    evaluation_id: str = Field(..., description="Unique evaluation session identifier")
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Timestamp when evaluation report was compiled"
    )
    rule_id: str = Field(..., description="Target detection rule evaluated")
    rule_version: str = Field(..., description="Target detection rule version")
    scenario_counts: dict[str, int] = Field(
        default_factory=dict, description="Distribution of experiment executions by scenario"
    )
    metrics: EvaluationMetrics = Field(..., description="Aggregated statistical metrics")
    experiments: list[ExperimentRecord] = Field(
        default_factory=list, description="List of individual experiment records"
    )
    research_disclaimer: str = Field(
        default=(
            "Laboratory evaluation result only. Measures detectability of predefined synthetic C2-like "
            "behavioral sequences under controlled conditions. Does not assert real-world malware detection "
            "capabilities, threat actor attribution, or universal blockchain security efficacy."
        ),
        description="Statement of laboratory boundaries and research integrity"
    )
